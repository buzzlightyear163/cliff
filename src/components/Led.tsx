export default function Led({
  text,
  pitch = 4,
  color = "var(--ink)",
  dim = true,
  label,
}: {
  text: string;
  pitch?: number;
  color?: string;
  dim?: boolean;
  label?: string;
}) {
  const chars = text.toUpperCase().split("");
  const dots: JSX.Element[] = [];
  let col = 0;
  chars.forEach((ch, ci) => {
    const g = F[ch] ?? F[" "];
    g.forEach((row, r) =>
      row.split("").forEach((bit, c) => {
        const on = bit === "1";
        if (!on && !dim) return;
        dots.push(
          <circle
            key={`${ci}-${r}-${c}`}
            cx={(col + c) * pitch + pitch / 2}
            cy={r * pitch + pitch / 2}
            r={on ? pitch * 0.38 : pitch * 0.14}
            fill={on ? color : "var(--dot)"}
          />,
        );
      }),
    );
    col += g[0].length + 1;
  });
  const w = Math.max(0, col - 1) * pitch;
  const h = 7 * pitch;
  return (
    <svg className="led" width={w} height={h} viewBox={`0 0 ${w} ${h}`} role="img" aria-label={label ?? text}>
      {dots}
    </svg>
  );
}
